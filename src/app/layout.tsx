import type { Metadata } from "next";
import { Exo } from "next/font/google";
import "./globals.css";
import Navbar from "./_LayoutPages/Navbar/page";
import { Toaster } from "@/components/ui/toast";
import { CartContextProvider } from "@/context/cartContext";
import { MysessionProvider} from "./_LayoutPages/MysessionProvider/MysessionProvider";
import { getServerSession } from "next-auth";
import { authOption } from "@/next-auth/authOption";
import { cn } from "@/lib/utils";

const ExoFont = Exo({
  variable: "--font-Roboto",
  weight: ["100", "500", "700"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const session = await getServerSession(authOption)

  return (
    <html
      lang="en"
      className={cn("h-full", "antialiased", ExoFont.className, "font-sans")}
    >
      <body className="min-h-full flex flex-col">
        <CartContextProvider>
        <MysessionProvider mySession={session}>
          <Navbar />
          {children}
          <Toaster />
        </MysessionProvider>
        </CartContextProvider>
        </body>

    </html>
  );
}
